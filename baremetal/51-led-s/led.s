.global _start            /* 导出裸机入口符号 */

/*
 * 程序从 _start 开始执行，依次使能时钟、配置 GPIO，
 * 最后通过输出低电平点亮 LED。
 */

_start:

/* ------------------------------------------------ */
/* 1. 打开全部 CCM 时钟门控                           */
/* ------------------------------------------------ */

ldr r0, =0x020C4068      /* CCM_CCGR0 寄存器地址 */
ldr r1, =0xFFFFFFFF      /* 每组时钟门控均设置为始终开启 */
str r1, [r0]

ldr r0, =0x020C406C      /* CCM_CCGR1 寄存器地址 */
str r1, [r0]

ldr r0, =0x020C4070      /* CCM_CCGR2 寄存器地址 */
str r1, [r0]

ldr r0, =0x020C4074      /* CCM_CCGR3 寄存器地址 */
str r1, [r0]

ldr r0, =0x020C4078      /* CCM_CCGR4 寄存器地址 */
str r1, [r0]

ldr r0, =0x020C407C      /* CCM_CCGR5 寄存器地址 */
str r1, [r0]

ldr r0, =0x020C4080      /* CCM_CCGR6 寄存器地址 */
str r1, [r0]


/* ------------------------------------------------ */
/* 2. 将 GPIO1_IO03 复用为 GPIO 功能                  */
/* ------------------------------------------------ */

ldr r0, =0x020E0068      /* SW_MUX_GPIO1_IO03 寄存器地址 */
ldr r1, =0x5             /* MUX_MODE=5 选择 GPIO 功能 */
str r1, [r0]


/* ------------------------------------------------ */
/* 3. 配置 GPIO1_IO03 PAD 电气属性                    */
/* ------------------------------------------------ */
/*
 * bit16 HYS=0：关闭迟滞；bit15:14 PUS=00：100K 下拉；
 * bit13 PUE=0：保持器；bit12 PKE=1：使能上拉/保持器；
 * bit11 ODE=0：关闭开漏；bit7:6 SPEED=10：100 MHz；
 * bit5:3 DSE=110：R0/6 驱动强度；bit0 SRE=0：慢转换速率。
 */

ldr r0, =0x020E02F4      /* SW_PAD_GPIO1_IO03 寄存器地址 */
ldr r1, =0x10B0          /* 与上述字段对应的 PAD 配置值 */
str r1, [r0]


/* ------------------------------------------------ */
/* 4. 将 GPIO1_IO03 设置为输出                        */
/* ------------------------------------------------ */

ldr r0, =0x0209C004      /* GPIO1_GDIR 寄存器地址 */
ldr r1, =0x00000008      /* bit3=1，GPIO1_IO03 输出 */
str r1, [r0]


/* ------------------------------------------------ */
/* 5. 输出低电平点亮 LED                             */
/* ------------------------------------------------ */
/*
 * 开发板 LED 采用低电平有效连接，因此 GPIO1_IO03 输出低电平时点亮。
 */

ldr r0, =0x0209C000      /* GPIO1_DR 寄存器地址 */
ldr r1, =0x0             /* 输出低电平 */
str r1, [r0]


/* ------------------------------------------------ */
/* 保持当前输出状态                                  */
/* ------------------------------------------------ */

loop:
    b loop               /* 裸机程序无返回路径 */

.section .note.GNU-stack,"",%progbits
